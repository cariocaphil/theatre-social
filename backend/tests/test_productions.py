"""Tests for the Production catalogue API (`/api/v1/productions`).

These tests exercise the real database (see `conftest.py`): a reachable
PostgreSQL instance is required (e.g. `podman compose up -d postgres`).
"""

import uuid

import pytest


async def _create(client, **overrides) -> dict:
    payload = {"title": "Default Test Production", **overrides}
    response = await client.post("/api/v1/productions", json=payload)
    assert response.status_code == 201, response.text
    return response.json()


# --- Creation and validation -------------------------------------------------


@pytest.mark.asyncio
async def test_create_with_only_title(client_factory):
    async with client_factory() as client:
        body = await _create(client, title="Impro Night Berlin")

    assert body["title"] == "Impro Night Berlin"
    assert body["slug"] == "impro-night-berlin"
    for field in (
        "description",
        "work_title",
        "creator_names",
        "company_name",
        "director_name",
        "venue_name",
        "city",
        "country_code",
        "premiere_date",
        "closing_date",
    ):
        assert body[field] is None
    assert uuid.UUID(body["id"])
    assert body["created_at"]
    assert body["updated_at"]


