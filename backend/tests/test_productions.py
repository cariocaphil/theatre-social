# --- Pagination and ordering -----------------------------------------------


@pytest.mark.asyncio
async def test_pagination_total_limit_offset(client_factory):
    async with client_factory() as client:
        for i in range(5):
            await _create(client, title=f"Paginated Show {i}")

        first_page = await client.get("/api/v1/productions", params={"limit": 2, "offset": 0})
        second_page = await client.get("/api/v1/productions", params={"limit": 2, "offset": 2})

    assert first_page.json()["total"] == 5
    assert len(first_page.json()["items"]) == 2
    assert first_page.json()["limit"] == 2
    assert first_page.json()["offset"] == 0

    assert len(second_page.json()["items"]) == 2
    assert second_page.json()["offset"] == 2

    first_ids = {item["id"] for item in first_page.json()["items"]}
    second_ids = {item["id"] for item in second_page.json()["items"]}
    assert first_ids.isdisjoint(second_ids)


