@pytest.mark.asyncio
async def test_session_remains_usable_after_integrity_error(client_factory):
    """After a rolled-back IntegrityError, the same request-scoped session
    (and the app as a whole) must still be able to serve further requests
    without leftover broken transaction state.
    """

    async with client_factory() as client:
        await _create(client, title="First", slug="dup-check")
        conflict = await client.post(
            "/api/v1/productions", json={"title": "Second", "slug": "dup-check"}
        )
        assert conflict.status_code == 409

        # A subsequent, unrelated request must succeed normally.
        follow_up = await client.post("/api/v1/productions", json={"title": "Perfectly Fine"})
        assert follow_up.status_code == 201


# --- Seed data ---------------------------------------------------------------


@pytest.mark.asyncio
async def test_seed_command_is_idempotent_and_covers_required_variety():
    from app.db.seed import seed

    await seed()
    await seed()  # running twice must not create duplicates

    from sqlalchemy import select

    from app.db.session import async_session_factory
    from app.models.production import Production

    async with async_session_factory() as session:
        result = await session.execute(select(Production))
        productions = result.scalars().all()

    assert len(productions) >= 12
    assert any(p.work_title is not None for p in productions)
    assert any(p.work_title is None for p in productions)
    assert any(p.venue_name is not None for p in productions)
    assert any(p.venue_name is None for p in productions)
